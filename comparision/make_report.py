"""Collect completed comparison CSVs into the reproducible results/REPORT.md."""
import glob, json, os
import pandas as pd

import common

O = common.OUT
raw = pd.concat([pd.read_csv(f) for f in glob.glob(os.path.join(O, "regression_raw_*.csv")) if "quick" not in f], ignore_index=True)
raw = raw[raw["ok"]]
expr = {}
for f in glob.glob(os.path.join(O, "regression_expressions_*.json")):
    if "quick" not in f:
        expr.update(json.load(open(f)))

# mean over seeds within a fold first, then mean / sd over folds
per_fold = raw.groupby(["case", "feature_set", "scheme", "model", "fold"], as_index=False)[["test_R2", "test_RMSE", "test_NRMSE", "train_R2"]].mean()
summ = per_fold.groupby(["case", "feature_set", "scheme", "model"]).agg(
    folds=("fold", "size"), R2=("test_R2", "mean"), R2_sd=("test_R2", "std"), RMSE=("test_RMSE", "mean"),
    NRMSE=("test_NRMSE", "mean"), train_R2=("train_R2", "mean")).reset_index()
summ.to_csv(os.path.join(O, "regression_summary_all.csv"), index=False)

ORDER = ["Pathway ln-form", "FEX (1-var)", "FEX", "SINDy (STLSQ)", "PySR", "MLP"]
SCHEMES = [s for s in ("random", "chrono", "blocked5", "site") if s in set(summ.scheme)]


# ------------------------------------------------------------------------------------------------ report
def md(df, cols, fmt):
    h = "| " + " | ".join(cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    return h + "\n".join("| " + " | ".join(fmt.get(c, str)(r[c]) for c in cols) + " |" for _, r in df.iterrows()) + "\n"


f3 = lambda x: "n/a" if pd.isna(x) else f"{x:.3f}"
L = ["# Comparison with baselines (reviewer point 6)\n",
     "Generated by `make_report.py` from `results/*.csv`. Held-out R² is computed on data never used for fitting or tuning.\n"]
for case in summ.case.unique():
    L.append(f"\n## {case}\n")
    for sch in SCHEMES:
        d = summ[(summ.case == case) & (summ.scheme == sch)]
        if d.empty:
            continue
        L.append(f"\n**Split: {sch}**\n")
        t = d.pivot_table(index="model", columns="feature_set", values="R2").reindex([m for m in ORDER if m in set(d.model)])
        t = t.reset_index()
        L.append(md(t, list(t.columns), {c: f3 for c in t.columns if c != "model"}))
if "scheme" in summ:
    L.append("\n## Fitted expressions (first fold, first seed)\n")
    for k, v in sorted(expr.items()):
        if "|chrono|" in k:
            L.append(f"- `{k}`: {v}\n")
pr = os.path.join(O, "path_recovery_summary.csv")
if os.path.exists(pr):
    L.append("\n## Path recovery: Sci-Miner vs definition-use chains vs slicing\n")
    L.append(md(pd.read_csv(pr), list(pd.read_csv(pr).columns), {c: f3 for c in pd.read_csv(pr).columns if c not in ("method",)}))
    pc = pd.read_csv(os.path.join(O, "path_recovery_cases.csv")).drop(columns=["du_chain"], errors="ignore")
    L.append("\nCase studies (slice sizes are numbers of assignment statements):\n\n")
    cols = ["query", "sci_miner", "sci_miner_equations", "du_found", "du_stmts", "du_max_var_degree", "slice_global_stmts", "slice_file_stmts",
            "slice_file_precision", "slice_file_recall"]
    L.append(md(pc, cols, {c: f3 for c in cols if c not in ("query", "sci_miner")}))
open(os.path.join(O, "REPORT.md"), "w", encoding="utf-8").write("".join(L))
print("wrote REPORT.md")
